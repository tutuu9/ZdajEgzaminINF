/** The same shared block, checked on one of the two copied pages. */
function copiedLayout(path: string): StudyActivity {
  return edit(
    `copy-${path.replace('.html', '')}`,
    `Przenieś wspólny układ do ${path}`,
    path,
    `Cały pusty ${path}.`,
    'Wszystkie trzy strony mają ten sam head, nagłówek, menu i stopkę; różni je tylko blok główny. Skopiuj gotowy index.html i usuń zawartość main, zamiast przepisywać układ od nowa.',
    `Skopiuj kod index.html do ${path} i zostaw pusty main.`,
    '<main></main>',
    [
      html(path, 'html[lang|="pl" i]'),
      html(path, 'title', { text: 'Montaż paneli podłogowych' }),
      html(path, 'link[rel="stylesheet"]', { attribute: 'href', equals: style }),
      html(path, 'header img[alt="firma usługowa"]', { attribute: 'src', equals: banner }),
      html(path, 'nav a', { minCount: 3 }),
      html(path, 'footer h5', { text: 'Autor strony:' }),
      html(path, 'main'),
    ],
  );
}

