/** These are original learning questions, not a reproduction of the CKE question bank. */
export const questions: QuestionRevision[] = Object.entries(seeds).flatMap(([topicId, rows]) =>
  rows.map((row, index) => {
    const [prompt, correct, wrong1, wrong2, wrong3, reference, level = 'beginner'] = row;
    const choices = [correct, wrong1, wrong2, wrong3];
    const offset = index % 4;
    const rotated = [...choices.slice(offset), ...choices.slice(0, offset)];
    const options = rotated.map(([text, explanation], optionIndex) => ({
      id: `o${optionIndex + 1}`,
      text,
      explanation,
    }));
    return {
      id: `${topicId}-${String(index + 1).padStart(2, '0')}`,
      version: topicId === 'html-css' && [12, 13].includes(index) ? 2 : 1,
      topicId,
      level,
      prompt,
      options,
      correctOptionId: options.find((option) => option.text === correct[0])!.id,
      explanation: correct[1],
      reference,
    };
  }),
);
